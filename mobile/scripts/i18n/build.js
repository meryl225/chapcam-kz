// Builds src/i18n/en.js from strings.json (French source strings) + en-part*.txt (one English line per source string, "=" = not user-facing).
const fs = require('fs')
const path = require('path')
const src = require('./strings.json')
const lines = ['en-part1.txt', 'en-part2.txt', 'en-part3.txt'].flatMap((f) => fs.readFileSync(path.join(__dirname, f), 'utf8').replace(/\n$/, '').split('\n'))
if (lines.length !== src.length) throw new Error(`Line count mismatch: ${lines.length} translations for ${src.length} strings`)
const dict = {}
src.forEach(({ k }, i) => { const en = lines[i]; if (en && en !== '=' && en !== k) dict[k] = en })
const out = `// Generated by scripts/i18n/build.js. Edit scripts/i18n/en-part*.txt, then run: node scripts/i18n/build.js\nexport const EN = ${JSON.stringify(dict, null, 1)}\n`
fs.writeFileSync(path.join(__dirname, '../../src/i18n/en.js'), out)
console.log('entries', Object.keys(dict).length)
